namespace MazyPlatform.SharedKernel.Domain.Abstractions;

/// <summary>
/// Маркерный интерфейс для доменных сервисов.
/// Используется для обозначения классов, содержащих бизнес-логику,
/// которая не принадлежит конкретной сущности или объекту-значению.
/// </summary>
/// <remarks>
/// Доменные сервисы применяются когда:
/// <list type="bullet">
/// <item><description>Операция включает несколько агрегатов или сущностей</description></item>
/// <item><description>Логика не имеет естественного места в агрегате или сущности</description></item>
/// <item><description>Операция представляет важную концепцию предметной области</description></item>
/// </list>
/// <para>
/// Доменные сервисы должны быть stateless и содержать только доменную логику.
/// Зависимости (репозитории, другие сервисы) внедряются через конструктор и сохраняются в readonly-полях,
/// что позволяет не передавать их в каждый метод явно.
/// </para>
/// </remarks>
public interface IDomainService;
